package com.tripbudget.tripbudget_core.notification.enums;

public enum NotificationType {
    MEMBER_INVITED, MEMBER_INVITATION_ACCEPTED, MEMBER_INVITATION_DECLINED, MEMBER_INVITATION_CANCELLED,
    MEMBER_ADDED, MEMBER_APPROVAL_REQUIRED, MEMBER_PENDING, MEMBER_APPROVED,
    MEMBER_ROLE_CHANGED, MEMBER_REMOVED, MEMBER_LEFT,
    ACTIVITY_REMINDER, TRIP_REMINDER, TRIP_CANCELLED,
    EXPENSE_CREATED, EXPENSE_UPDATED, EXPENSE_DELETED,
    SETTLEMENT_RECORDED, SETTLEMENT_DELETED, SETTLEMENT_CONFIRMATION_REQUIRED, SETTLEMENT_UPDATED;

    public boolean minimalAccess() {
        return this == MEMBER_PENDING || this == MEMBER_REMOVED || this == MEMBER_INVITED
            || this == MEMBER_INVITATION_DECLINED || this == MEMBER_INVITATION_CANCELLED;
    }
}
