CREATE TABLE trip_core.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL,
    recipient_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    trip_id BIGINT NOT NULL REFERENCES trip_core.trips(id) ON DELETE CASCADE,
    target_id BIGINT,
    type VARCHAR(50) NOT NULL CHECK (type IN ('TRIP_MEMBER_ADDED', 'TRIP_INVITATION_PENDING',
        'TRIP_MEMBER_APPROVAL_REQUIRED', 'TRIP_MEMBERSHIP_APPROVED', 'TRIP_ACTIVITY_CREATED', 'TRIP_ACTIVITIES_GENERATED')),
    read_at TIMESTAMPTZ,
    is_del BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_notifications_event_recipient UNIQUE(event_id, recipient_id)
);
CREATE INDEX idx_notifications_recipient_created ON trip_core.notifications(recipient_id, created_at DESC, id DESC);
CREATE INDEX idx_notifications_unread ON trip_core.notifications(recipient_id, trip_id) WHERE read_at IS NULL AND is_del = FALSE;
CREATE TABLE trip_core.realtime_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL,
    recipient_id BIGINT NOT NULL,
    notification_id BIGINT REFERENCES trip_core.notifications(id) ON DELETE CASCADE,
    event_type VARCHAR(50) NOT NULL CHECK (event_type IN ('notification.created', 'notification.read-state-changed')),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'PROCESSING', 'DISPATCHED', 'FAILED')),
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    lease_until TIMESTAMPTZ,
    claim_token UUID,
    dispatched_at TIMESTAMPTZ,
    is_del BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_outbox_event_recipient UNIQUE(event_id, recipient_id)
);
CREATE INDEX idx_outbox_due ON trip_core.realtime_outbox(next_attempt_at, id) WHERE status IN ('PENDING', 'PROCESSING');
CREATE INDEX idx_outbox_cleanup ON trip_core.realtime_outbox(dispatched_at) WHERE status = 'DISPATCHED';
COMMIT;
